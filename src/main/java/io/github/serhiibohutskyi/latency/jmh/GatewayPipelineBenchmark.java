package io.github.serhiibohutskyi.latency.jmh;

import io.github.serhiibohutskyi.latency.domain.*;
import org.openjdk.jmh.annotations.*;

import java.nio.ByteBuffer;
import java.nio.ByteOrder;
import java.util.concurrent.TimeUnit;

/**
 * The whole gateway pipeline -- decode, risk check, encode -- behind {@code @Benchmark}.
 *
 * <p>This exists to make one point precisely. The usual complaint about microbenchmarks is
 * that they are "not realistic", which is vague and a bit unfair to JMH: you can put an
 * entire pipeline behind {@code @Benchmark} and JMH will measure it perfectly well. Here
 * is the entire pipeline, measured perfectly well.
 *
 * <p>The real limit is more specific. <b>JMH is closed-loop.</b> There is no arrival
 * process: the next operation begins when the previous one returns, so the offered load is
 * generated by the system's own speed and no queue can ever form. What comes out of this
 * class is <i>service time at 100% utilisation of one thread</i>. If the pipeline stalls
 * for 10 ms, JMH simply does less work for 10 ms -- which is not what a market does.
 *
 * <p>Compare the number this reports against the {@code jlbh} command's end-to-end p50 at a
 * modest rate: they should broadly agree. Then compare it against the p99.9 as the rate
 * climbs in the {@code sweep} command, and watch them stop agreeing. That divergence is
 * queueing, and it is the thing this benchmark structurally cannot show you.
 */
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Warmup(iterations = 5, time = 1)
@Measurement(iterations = 8, time = 1)
@Fork(value = 3, jvmArgsAppend = {"-Xms2g", "-Xmx2g", "-XX:+AlwaysPreTouch"})
@State(Scope.Thread)
public class GatewayPipelineBenchmark {

    private final OrderDecoder decoder = new OrderDecoder();
    private final RiskEngine riskEngine = new RiskEngine();
    private final OrderEncoder encoder = new OrderEncoder();

    private final MutableOrder order = new MutableOrder();
    private final OrderMessageSource source = new OrderMessageSource();

    private ByteBuffer output;

    @Setup(Level.Trial)
    public void setUp() {
        output = ByteBuffer.allocateDirect(128).order(ByteOrder.LITTLE_ENDIAN);
    }

    @Benchmark
    public long pipeline() {
        decoder.decode(source.next(), order);

        long result = order.orderId();

        if (riskEngine.accept(order)) {
            output.clear();
            encoder.encode(output, order);
            result ^= output.getLong(0);
        }

        return result;
    }
}
